export const ROOM_BY_ID = new Map();
for (const rm of ENHANCED_ROOM_DB) {
  ROOM_BY_ID.set(rm.id.toLowerCase(), rm);
  for (const al of rm.aliases) {
    if (!ROOM_BY_ID.has(al.toLowerCase())) {
      ROOM_BY_ID.set(al.toLowerCase(), rm);
    }
  }
}

export function findRoomByIdOrAlias(queryId) {
  if (!queryId) return null;
  const clean = decodeURIComponent(String(queryId)).replace(/^#/, '').trim().toLowerCase();
  return ROOM_BY_ID.get(clean) || ENHANCED_ROOM_DB.find(
    item => item.room.toLowerCase() === clean || item.id.toLowerCase() === clean
  ) || null;
}

export function searchRooms(query) {
  const q = (query || '').trim().toLowerCase();
  if (!q) return [];
  const qNorm = q.replace(/tt/g, 't').replace(/[-_\s]+/g, ' ');
  return ENHANCED_ROOM_DB.filter(rm => {
    const fields = [rm.name, rm.room, rm.id, rm.floor, rm.category, ...(rm.aliases || [])];
    return fields.some(val => {
      const s = String(val).toLowerCase();
      return s.includes(q) || s.replace(/tt/g, 't').replace(/[-_\s]+/g, ' ').includes(qNorm);
    });
  });
}

