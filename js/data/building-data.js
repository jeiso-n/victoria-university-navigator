// Helper to create a concise room entry
// bounds: [xMin, zMin, xMax, zMax], door: [x, z]
function r(id, room, name, floor, category, bounds, door, opts = {}) {
  const floorDef = FLOOR_MAP[floor];
  return {
    id,
    room,
    name,
    floor,
    floorClass: floorDef ? floorDef.floorClass : '',
    levelIndex: floorDef ? floorDef.levelIndex : 0,
    category,
    bounds,
    center: [
      Number(((bounds[0] + bounds[2]) / 2).toFixed(2)),
      Number(((bounds[1] + bounds[3]) / 2).toFixed(2)),
    ],
    door,
    aliases: opts.aliases || [],
    anchor: opts.anchor || `../directions.html#${id}`,
    directionsText: opts.directionsText || '',
    image: opts.image || '',
    svgLabel: opts.svgLabel || '',
    verificationStatus: opts.verificationStatus || 'verified-svg',
    verificationNote: opts.verificationNote || '',
  };
}

